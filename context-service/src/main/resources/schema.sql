CREATE TABLE IF NOT EXISTS "UrbanAsset" (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo            VARCHAR(50) NOT NULL,
    nombre          VARCHAR(200),
    descripcion     VARCHAR(400),
    direccion       VARCHAR(200),
    latitud         NUMERIC(9,6) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud        NUMERIC(9,6) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    fuente          VARCHAR(50) NOT NULL,
    id_externo      VARCHAR(100) NOT NULL,
    actualizado_en  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (fuente, id_externo)
);

CREATE INDEX IF NOT EXISTS idx_context_asset_posicion ON "UrbanAsset" (latitud, longitud);

CREATE TABLE IF NOT EXISTS "WeatherObservation" (
    id              INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    municipio       VARCHAR(100) NOT NULL,
    estacion        VARCHAR(100),
    temperatura     NUMERIC(4,1) NOT NULL,
    humedad         NUMERIC(5,2) NOT NULL,
    estado_cielo    VARCHAR(100),
    viento          VARCHAR(100),
    precipitacion   NUMERIC(5,2) DEFAULT 0.0,
    observado_en    TIMESTAMP NOT NULL,
    ingerido_en     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fuente          VARCHAR(100) NOT NULL,
    calidad         VARCHAR(30) NOT NULL,
    UNIQUE (fuente, estacion, observado_en)
);

CREATE INDEX IF NOT EXISTS idx_weather_observed ON "WeatherObservation" (observado_en DESC);

CREATE TABLE IF NOT EXISTS "WeatherForecast" (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio                       VARCHAR(100) NOT NULL,
    fecha                           DATE NOT NULL,
    temperatura_min                 NUMERIC(4,1),
    temperatura_max                 NUMERIC(4,1),
    humedad                         NUMERIC(5,2),
    estado_cielo                    VARCHAR(100),
    probabilidad_precipitacion      NUMERIC(5,2),
    actualizado_en                  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fuente                          VARCHAR(100) NOT NULL,
    UNIQUE (municipio, fecha, fuente)
);
